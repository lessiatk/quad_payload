function cfg = config()
%CONFIG Налаштування розрахунку.
cfg.m_hi     = 30;      % кг, верхня межа пошуку навантаження
cfg.dm       = 0.5;     % кг, крок сітки (детерміновані розрахунки)
cfg.tol      = 1e-4;    % кг, точність бісекції
cfg.dm_mc    = 1.0;     % кг, крок сітки в Monte Carlo
cfg.tol_mc   = 1e-2;    % кг, точність бісекції в Monte Carlo
cfg.N_mc     = 500;     % реалізацій Monte Carlo (для фінального звіту >= 2000)
cfg.seed     = 42;
cfg.preset   = 'real';  % 'real' - реальні компоненти (real_params), 'ref' - узагальнена референсна конфігурація
cfg.m_target = 8;       % кг, значення для перевірки гіпотези "8 кг"

% Пороги модуля достовірності
cfg.E_crit     = 0.30;  % |еластичність| -> критично чутливий параметр
cfg.E_warn     = 0.05;  % |еластичність| -> помітний вплив
cfg.E_dep      = 0.01;  % вихід вважається залежним від параметра
cfg.n_top      = 6;     % скільки найвпливовіших параметрів показувати
cfg.rej_warn   = 0.05;  % частка відкинутих MC-вибірок
cfg.width_warn = 0.50;  % відносна ширина P5-P95 -> попередження
cfg.width_ok   = 0.20;  % ... для визнання результату достовірним
cfg.method_tol = 0.05;  % розбіжність методів
cfg.mc_conv_tol= 0.15;  % кг
cfg.E_density_max = 260;% Вт*год/кг
end
