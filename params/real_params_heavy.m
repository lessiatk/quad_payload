function P = real_params_heavy()
%REAL_PARAMS_HEAVY Друга конфігурація: потужніший мотор, пропелер, ESC і посилені промені.
%   База - real_params (рама Tarot X4, батарея Tattu 16 А*год), замінено:
%   мотор -> T-Motor V605 KV210 (12S), пропелер -> T-Motor V22x7.4, ESC -> FLAME 80A 12S V2.0,
%   промені -> труба Ш35x2 мм (каталожних квадрокоптерних рам з паспортом на >8 кг при базі 960 мм
%   не знайдено, тому пластини Tarot X4 лишено, а промені підсилено - це припущення).
P = real_params();

% --- Мотор T-Motor V605 KV210: 385 г з кабелем, R = 48 мОм, I0 = 1.6 А (18 В), пік 70 А/180 с, 12.76 кгс ---
P = ov(P, 'Kv',      210,   205,   215,   'datasheet');
P = ov(P, 'Rm',      0.048, 0.045, 0.051, 'datasheet');
P = ov(P, 'I0',      1.6,   1.3,   1.9,   'datasheet');
P = ov(P, 'I_cont',  35,    30,    70,    'assumed');             % паспорт: 70 А лише 180 с; 98 C при 80 % газу (38.7 А) за 10 хв
P = ov(P, 'm_motor', 0.385, 0.380, 0.390, 'datasheet');
% --- Пропелер T-Motor V22x7.4: C_T, C_P виведено зі стендової таблиці V605 + V22x7.4 (12S, ρ стенду припущено 1.2) ---
P = ov(P, 'CT',      0.075, 0.072, 0.078, 'datasheet');
P = ov(P, 'CP',      0.0215,0.0205,0.0225,'datasheet');
P = ov(P, 'm_prop',  0.096, 0.090, 0.110, 'datasheet');          % 2 x 48 г (одиничний/подвійний вага у лістингах неоднозначна)
% --- ESC T-Motor FLAME 80A 12S V2.0 ---
P = ov(P, 'm_esc',   0.109, 0.094, 0.120, 'datasheet');
P = ov(P, 'I_esc_cont', 80, 80,    80,    'datasheet');
P = ov(P, 'R_esc',   0.141, 0.09,  0.19,  'assumed');            % калібрування за стендом: 46.60 В, 7036 об/хв

% --- Посилені промені: труба Ш35x2 (підібрано за власною частотою ~92 Гц: при тоншій трубі 2P оборотів
%     висіння потрапляє в резонанс і допустимої області за навантаженням немає) ---
P = ov(P, 'arm_OD',  0.035, 0.0335, 0.0365, 'assumed');
P = ov(P, 'arm_t',   0.002, 0.0018, 0.0022, 'assumed');
end

function P = ov(P, name, nom, lo, hi, src)
p = P.(name);
p.nom = nom; p.lo = lo; p.hi = hi; p.src = src;
P.(name) = p;
end
