function S = arm_structure(X, T, Q, m_tip)
%ARM_STRUCTURE Аналітична модель променя як консольної балки (Ейлер-Бернуллі).
%
%   Розрахункова схема: труба, жорстко защемлена в затискачі (x=0),
%   на кінці (x=L) - тяга T, реактивний момент мотора Q, зосереджена маса.
%   Критична ділянка - корінь променя в затискачі: max згинальний момент
%   M = T*L, кручення Q, концентрація напружень/зминання (коеф. k_joint).
%   Власна вага і вага мотора зменшують момент - не враховано (в запас).

OD = X.arm_OD; ID = OD - 2*X.arm_t; L = X.L_arm; E = X.E_arm;
I  = pi/64 * (OD^4 - ID^4);          % м^4
J  = 2*I;                            % полярний момент
c  = OD/2;
A  = pi/4 * (OD^2 - ID^2);

M     = T*L;
sigma = M*c/I;                       % згин
tau   = Q*c/J;                       % кручення
svm   = sqrt(sigma^2 + 3*tau^2);     % еквівалентне (фон Мізес)

S.I = I; S.J = J; S.A = A; S.EI = E*I;
S.M_root = M; S.sigma = sigma; S.tau = tau; S.sigma_vm = svm;
S.sigma_allow = X.sigma_ult * X.k_joint / X.SF;
S.delta = T*L^3 / (3*E*I);           % прогин кінця
S.theta = T*L^2 / (2*E*I);           % кут повороту кінця (нахил мотора), рад
S.m_arm = X.rho_cf * A * L;
% Перша власна частота (метод Релея: маса на кінці + 33/140 маси балки)
k = 3*E*I/L^3;
S.f_n = sqrt(k / (m_tip + 33/140*S.m_arm)) / (2*pi);   % Гц
end
